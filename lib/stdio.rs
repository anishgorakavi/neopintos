/// A number base and how to print it.
struct Radix {
    base: u64,
    digit_chars: &'static [u8; 16],
    /// The letter after `0` for the `#` flag (`x` in `0xff`); `None` for bases without one.
    alternate_prefix: Option<u8>,
    /// How many digits go between commas with the `'` flag.
    group_size: usize,
}

const DECIMAL: Radix = Radix { base: 10, digit_chars: b"0123456789abcdef", alternate_prefix: None, group_size: 3 };
const OCTAL: Radix = Radix { base: 8, digit_chars: b"0123456789abcdef", alternate_prefix: None, group_size: 3 };
const HEX_LOWER: Radix = Radix { base: 16, digit_chars: b"0123456789abcdef", alternate_prefix: Some(b'x'), group_size: 4 };
const HEX_UPPER: Radix = Radix { base: 16, digit_chars: b"0123456789ABCDEF", alternate_prefix: Some(b'X'), group_size: 4 };

/// Size of the digit buffer; precision padding stops one short so `#` octal still fits.
const DIGIT_BUFFER_LEN: usize = 64;

/// Digits of a number, collected least-significant first (printing walks it backwards).
struct DigitBuffer {
    chars: [u8; DIGIT_BUFFER_LEN],
    len: usize,
}

impl DigitBuffer {
    fn new() -> Self {
        Self { chars: [0; DIGIT_BUFFER_LEN], len: 0 }
    }

    /// Bounds-checked: a bug that overfills the buffer panics instead of corrupting memory.
    fn push(&mut self, ch: u8) {
        self.chars[self.len] = ch;
        self.len += 1;
    }

    fn last(&self) -> Option<u8> {
        self.len.checked_sub(1).map(|index| self.chars[index])
    }

    /// Most-significant digit first, ready to print.
    fn in_print_order(&self) -> impl Iterator<Item = u8> + '_ {
        self.chars[..self.len].iter().rev().copied()
    }
}

/// Prints one integer according to the directive.
///
/// `magnitude` is the absolute value; for signed conversions `is_negative` supplies the
/// sign separately (this is how the most negative number is handled without overflow).
fn format_integer(
    magnitude: u64,
    is_signed: bool,
    is_negative: bool,
    radix: &Radix,
    directive: &Directive,
    sink: &mut dyn CharSink,
) {
    let flags = directive.flags;

    // Unsigned conversions never print a sign, even if a flag asks for one.
    let sign_char = match (is_signed, is_negative) {
        (false, _) => None,
        (true, true) => Some(b'-'),
        (true, false) if flags.has(Flags::FORCE_SIGN) => Some(b'+'),
        (true, false) if flags.has(Flags::SPACE_FOR_SIGN) => Some(b' '),
        (true, false) => None,
    };

    // `0x` is only printed for non-zero hexadecimal values with the `#` flag.
    let prefix_char = match radix.alternate_prefix {
        Some(letter) if flags.has(Flags::ALTERNATE_FORM) && magnitude != 0 => Some(letter),
        _ => None,
    };

    let mut digits = DigitBuffer::new();
    let mut remaining = magnitude;
    let mut digits_so_far = 0;
    while remaining > 0 {
        if flags.has(Flags::GROUP_THOUSANDS) && digits_so_far > 0 && digits_so_far % radix.group_size == 0 {
            digits.push(b',');
        }
        digits.push(radix.digit_chars[(remaining % radix.base) as usize]);
        remaining /= radix.base;
        digits_so_far += 1;
    }

    // Left-pad with zeros up to the precision.  Zero printed with precision 0 is empty;
    // with no precision it is "0".  (Capped so the buffer cannot overflow.)
    let min_digits = directive.precision.unwrap_or(1);
    while digits.len < min_digits && digits.len < DIGIT_BUFFER_LEN - 1 {
        digits.push(b'0');
    }
    // `#` with octal guarantees a leading zero.
    if flags.has(Flags::ALTERNATE_FORM) && radix.base == 8 && digits.last() != Some(b'0') {
        digits.push(b'0');
    }

    let prefix_len = if prefix_char.is_some() { 2 } else { 0 };
    let sign_len = sign_char.is_some() as usize;
    let used = digits.len + prefix_len + sign_len;
    let padding = directive.min_width.saturating_sub(used);

    if !flags.has(Flags::LEFT_JUSTIFY) && !flags.has(Flags::ZERO_PAD) {
        sink.put_repeated(b' ', padding);
    }
    if let Some(sign) = sign_char {
        sink.put_char(sign);
    }
    if let Some(letter) = prefix_char {
        sink.put_char(b'0');
        sink.put_char(letter);
    }
    if flags.has(Flags::ZERO_PAD) {
        sink.put_repeated(b'0', padding);
    }
    digits.in_print_order().for_each(|digit| sink.put_char(digit));
    if flags.has(Flags::LEFT_JUSTIFY) {
        sink.put_repeated(b' ', padding);
    }
}

/// Prints text (`%s` or `%c`) padded to the directive's width.
fn format_text(text: &[u8], directive: &Directive, sink: &mut dyn CharSink) {
    let padding = directive.min_width.saturating_sub(text.len());
    let left_justify = directive.flags.has(Flags::LEFT_JUSTIFY);
    if !left_justify {
        sink.put_repeated(b' ', padding);
    }
    sink.put_bytes(text);
    if left_justify {
        sink.put_repeated(b' ', padding);
    }
}

/// Prints a message in place of an unsupported or unknown conversion.
fn format_unsupported(conversion: u8, reason: &[u8], sink: &mut dyn CharSink) {
    sink.put_bytes(b"<<no %");
    sink.put_char(conversion);
    sink.put_bytes(reason);
}

// ---------------------------------------------------------------------------------------
// The engine.
// ---------------------------------------------------------------------------------------

/// Formats `template` (a C string without its NUL) with `args` into `sink`.
///
/// Literal characters are copied; `%%` prints `%`; every other `%…` directive is parsed,
/// consumes its arguments and prints one value.  Floating point and `%n` are refused.
pub fn format(template: &[u8], args: &mut impl Args, sink: &mut dyn CharSink) {
    let mut cursor = Cursor { template, position: 0 };
    while !cursor.at_end() {
        let ch = cursor.peek();
        cursor.advance(1);
        if ch != b'%' {
            sink.put_char(ch);
            continue;
        }
        if cursor.peek() == b'%' {
            sink.put_char(b'%');
            cursor.advance(1);
            continue;
        }

        let mut directive = parse_directive(&mut cursor, args);
        let conversion = cursor.peek();
        match conversion {
            b'd' | b'i' => {
                let value = next_signed(directive.arg_size, args);
                format_integer(value.unsigned_abs(), true, value < 0, &DECIMAL, &directive, sink);
            }
            b'o' | b'u' | b'x' | b'X' => {
                let value = next_unsigned(directive.arg_size, args);
                let radix = match conversion {
                    b'o' => &OCTAL,
                    b'u' => &DECIMAL,
                    b'x' => &HEX_LOWER,
                    _ => &HEX_UPPER,
                };
                format_integer(value, false, false, radix, &directive, sink);
            }
            b'c' => {
                // The argument is an `int`; only its low byte is a character.
                let ch = args.next_word() as u8;
                format_text(&[ch], &directive, sink);
            }
            b's' => {
                let max_len = directive.precision.unwrap_or(usize::MAX);
                let text = args.next_string(max_len);
                format_text(text, &directive, sink);
            }
            b'p' => {
                // A pointer prints as `%#x`.  The C code also discarded every other flag
                // (but kept width and precision); we match it.
                directive.flags = Flags::NONE.with(Flags::ALTERNATE_FORM);
                let address = args.next_word() as u64;
                format_integer(address, false, false, &HEX_LOWER, &directive, sink);
            }
            // No floating point in the kernel, and %n can be part of a security hole.
            b'f' | b'e' | b'E' | b'g' | b'G' | b'n' => format_unsupported(conversion, b" in kernel>>", sink),
            _ => format_unsupported(conversion, b" conversion>>", sink),
        }
        if cursor.at_end() {
            break; // template ended inside a directive; nothing left to skip
        }
        cursor.advance(1); // step past the conversion character
    }
}

