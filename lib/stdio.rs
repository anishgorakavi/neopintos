/// `printf` core used by the console: formats and sends each character to `output`.
///
/// # Safety
/// `format` is a C string; `args` supplies what it asks for; `output` may be called with `aux`.
#[no_mangle]
pub unsafe extern "C" fn __vprintf(format: *const c_char, mut args: VaList, output: OutputCallback, aux: *mut c_void) {
    // SAFETY: caller passes a valid C string and matching arguments.
    let (template, mut args) = unsafe { (ffi::c_str_bytes(format), CVarArgs::new(&mut args)) };
    self::format(template, &mut args, &mut CallbackSink { output, aux });
}

/// Variadic wrapper around [`__vprintf`].
///
/// # Safety
/// As [`__vprintf`].
#[no_mangle]
pub unsafe extern "C" fn __printf(format: *const c_char, output: OutputCallback, aux: *mut c_void, args: ...) {
    // SAFETY: forwarded.
    unsafe { __vprintf(format, args, output, aux) }
}

/// Like `vprintf()`, but stores into `buffer` (`buffer_size` bytes).  At most
/// `buffer_size - 1` characters are written, followed by a NUL, unless `buffer_size` is 0.
/// Returns the length the full output would have had.
///
/// # Safety
/// `buffer` is writable for `buffer_size` bytes; `format` and `args` as [`__vprintf`].
#[no_mangle]
pub unsafe extern "C" fn vsnprintf(buffer: *mut c_char, buffer_size: usize, format: *const c_char, mut args: VaList) -> c_int {
    // SAFETY: caller passes a writable buffer of that size, a valid C string and matching arguments.
    let (storage, template, mut args) = unsafe {
        (ffi::slice_from_raw_mut(buffer.cast::<u8>(), buffer_size), ffi::c_str_bytes(format), CVarArgs::new(&mut args))
    };
    let mut output = TruncatingBuffer::new(storage);
    self::format(template, &mut args, &mut output);
    output.finish() as c_int
}

/// # Safety
/// As [`vsnprintf`].
#[no_mangle]
pub unsafe extern "C" fn snprintf(buffer: *mut c_char, buffer_size: usize, format: *const c_char, args: ...) -> c_int {
    // SAFETY: forwarded.
    unsafe { vsnprintf(buffer, buffer_size, format, args) }
}

/// Writes formatted output to the console.
///
/// # Safety
/// `format` and the arguments as [`__vprintf`].
#[no_mangle]
pub unsafe extern "C" fn printf(format: *const c_char, args: ...) -> c_int {
    // SAFETY: forwarded to the console's `vprintf`, which takes the console lock.
    unsafe { sys::vprintf(format, args) }
}

