//! The printf family: Rust replacement for `lib/stdio.c` in the kernel.
//!
//! # How a `printf` call flows
//!
//! ```text
//!   C caller:   snprintf(buf, 16, "%5d|%s", 42, "hi")
//!                  │  (C ABI entry points, bottom of this file: raw pointers + C varargs)
//!                  ▼
//!   adapters:   TruncatingBuffer  (safe wrapper over the caller's buffer)
//!               CVarArgs          (safe wrapper over the C argument list)
//!                  │
//!                  ▼
//!   engine:     format(template, &mut args, &mut sink)      ← 100% safe Rust
//!                  │   walks the template; for each `%…` directive:
//!                  │     parse_directive → read the argument → format_integer / format_text
//!                  ▼
//!   sink:       CharSink::put_char(byte) — a buffer, or the C callback `output(ch, aux)`
//! ```
//!
//! The same engine drives every entry point; only the sink differs.  `vprintf`, `puts` and
//! `putchar` stay in `lib/kernel/console.c` because they take the console lock and drive
//! the serial/VGA hardware; `printf` here simply forwards to that C `vprintf`.  User
//! programs still build the original `stdio.c`.
//!
//! # Where the `unsafe` is
//!
//! The engine has none.  The unavoidable unsafe operations are confined to:
//!  * [`CVarArgs`]: reading C variadic arguments (the compiler cannot check that the
//!    caller passed the types the template asks for, in C or Rust);
//!  * the `extern "C"` entry points at the bottom, which turn raw pointers into slices via
//!    [`crate::ffi`] and then immediately work with safe types.
//!
//! Console output goes through [`crate::console::write_bytes`], a safe function.
//! Nothing here allocates or takes a lock itself, so it is usable from interrupt context.
//! Output is byte-for-byte what the C version produced: `rust/src/selftest_printf.rs`
//! checks fixtures generated by running the original C code.
use core::ffi::{c_char, c_int, c_void, VaList};
use core::fmt::Write as _;

use crate::console;
use crate::ffi;
use crate::rt::CBuf;
use crate::sys;

const _: () = assert!(core::mem::size_of::<usize>() == 4, "printf assumes a 32-bit target (ILP32)");

// ---------------------------------------------------------------------------------------
// Output sinks: where formatted characters go.
// ---------------------------------------------------------------------------------------

/// Receives the formatted output one byte at a time.
pub trait CharSink {
    fn put_char(&mut self, ch: u8);

    fn put_bytes(&mut self, bytes: &[u8]) {
        for &byte in bytes {
            self.put_char(byte);
        }
    }

    fn put_repeated(&mut self, ch: u8, times: usize) {
        for _ in 0..times {
            self.put_char(ch);
        }
    }
}

/// Collects output into a caller-provided buffer, truncating when it is full.
///
/// Mirrors `snprintf`: at most `capacity - 1` characters are stored so a NUL always fits,
/// but *every* character is counted so the caller learns the untruncated length.
pub struct TruncatingBuffer<'a> {
    storage: &'a mut [u8],
    chars_seen: usize,
}

impl<'a> TruncatingBuffer<'a> {
    pub fn new(storage: &'a mut [u8]) -> Self {
        Self { storage, chars_seen: 0 }
    }

    /// Stores the terminating NUL (if there is any room at all) and returns the number of
    /// characters the complete output has, whether or not they all fit.
    pub fn finish(self) -> usize {
        if let Some(last_index) = self.storage.len().checked_sub(1) {
            self.storage[self.chars_seen.min(last_index)] = 0;
        }
        self.chars_seen
    }
}

impl CharSink for TruncatingBuffer<'_> {
    fn put_char(&mut self, ch: u8) {
        let room_for_chars = self.storage.len().saturating_sub(1);
        if self.chars_seen < room_for_chars {
            self.storage[self.chars_seen] = ch;
        }
        self.chars_seen = self.chars_seen.wrapping_add(1);
    }
}

type OutputCallback = extern "C" fn(c_char, *mut c_void);

/// Forwards each character to a C callback `output(ch, aux)`; this is how
/// `lib/kernel/console.c` receives characters from [`__vprintf`].
struct CallbackSink {
    output: OutputCallback,
    aux: *mut c_void,
}

impl CharSink for CallbackSink {
    fn put_char(&mut self, ch: u8) {
        (self.output)(ch as c_char, self.aux);
    }
}

