/// Supplies the values that `%d`, `%s`, ... directives consume, in order.
pub trait Args {
    /// An `int`, `unsigned`, `long`, `ptrdiff_t`, `size_t` or pointer: all 32 bits here.
    fn next_word(&mut self) -> u32;
    /// A `long long` or `intmax_t`: 64 bits.
    fn next_double_word(&mut self) -> u64;
    /// A C string argument, limited to `max_len` bytes; NULL is shown as `(null)`.
    fn next_string(&mut self, max_len: usize) -> &[u8];
}

/// The argument list of a C variadic call.
///
/// This is the one place where trust is unavoidable: the C compiler does not check the
/// types of variadic arguments against the template, and neither can we.  The `unsafe`
/// constructor makes the caller state that promise once; the methods below rely on it.
pub struct CVarArgs<'a, 'list> {
    list: &'a mut VaList<'list>,
}

impl<'a, 'list> CVarArgs<'a, 'list> {
    /// # Safety
    /// The remaining arguments must match, in order and type, what the template will ask
    /// for, and every `%s` argument must be NULL or a valid NUL-terminated string.
    pub unsafe fn new(list: &'a mut VaList<'list>) -> Self {
        Self { list }
    }
}

impl Args for CVarArgs<'_, '_> {
    fn next_word(&mut self) -> u32 {
        // SAFETY: the constructor's contract says the next argument is a 32-bit value.
        unsafe { self.list.next_arg::<u32>() }
    }

    fn next_double_word(&mut self) -> u64 {
        // SAFETY: the constructor's contract says the next argument is a 64-bit value.
        unsafe { self.list.next_arg::<u64>() }
    }

    fn next_string(&mut self, max_len: usize) -> &[u8] {
        let address = self.next_word() as usize;
        if address == 0 {
            return b"(null)";
        }
        // SAFETY: the constructor's contract says this is a valid C string.
        unsafe { ffi::c_str_bytes_bounded(address as *const u8, max_len) }
    }
}

// ---------------------------------------------------------------------------------------
// Parsing a directive such as `%-+08.3lld`.
// ---------------------------------------------------------------------------------------

/// The flag characters after `%`.  Stored as bits in one byte.
#[derive(Clone, Copy)]
struct Flags(u8);

impl Flags {
    const NONE: Flags = Flags(0);
    /// `-`: pad on the right instead of the left.
    const LEFT_JUSTIFY: u8 = 1 << 0;
    /// `+`: always print a sign.
    const FORCE_SIGN: u8 = 1 << 1;
    /// ` `: print a space where a `+` would go.
    const SPACE_FOR_SIGN: u8 = 1 << 2;
    /// `#`: alternate form (`0x` prefix, leading `0` for octal).
    const ALTERNATE_FORM: u8 = 1 << 3;
    /// `0`: pad with zeros instead of spaces.
    const ZERO_PAD: u8 = 1 << 4;
    /// `'`: group digits with commas.
    const GROUP_THOUSANDS: u8 = 1 << 5;

    fn has(self, flag: u8) -> bool {
        self.0 & flag != 0
    }
    fn with(self, flag: u8) -> Flags {
        Flags(self.0 | flag)
    }
    fn without(self, flag: u8) -> Flags {
        Flags(self.0 & !flag)
    }
}

/// How many bytes of the argument the directive consumes (`hh`, `h`, none, `l`, ...).
#[derive(Clone, Copy)]
enum ArgSize {
    Char,
    Short,
    Int,
    IntMax,
    Long,
    LongLong,
    PtrDiff,
    Size,
}

/// Everything between `%` and the conversion character.
struct Directive {
    flags: Flags,
    /// Minimum output width; shorter output is padded.
    min_width: usize,
    /// Minimum digits for integers, maximum characters for strings; `None` if not given.
    precision: Option<usize>,
    arg_size: ArgSize,
}

/// Reads the template one byte at a time; reading past the end yields NUL, like C.
struct Cursor<'a> {
    template: &'a [u8],
    position: usize,
}

impl Cursor<'_> {
    fn peek(&self) -> u8 {
        self.peek_ahead(0)
    }

    fn peek_ahead(&self, distance: usize) -> u8 {
        self.template.get(self.position + distance).copied().unwrap_or(0)
    }

    fn advance(&mut self, count: usize) {
        self.position += count;
    }

    fn at_end(&self) -> bool {
        self.peek() == 0
    }

    /// Consumes a run of decimal digits.  Wraps on overflow, as the C `int` math did.
    fn parse_decimal(&mut self) -> i32 {
        let mut value = 0i32;
        while self.peek().is_ascii_digit() {
            let digit = (self.peek() - b'0') as i32;
            value = value.wrapping_mul(10).wrapping_add(digit);
            self.advance(1);
        }
        value
    }
}

/// Parses flags, width, precision and size, leaving the cursor on the conversion
/// character.  A `*` width or precision takes its value from the argument list.
fn parse_directive(cursor: &mut Cursor, args: &mut impl Args) -> Directive {
    let mut flags = Flags::NONE;
    loop {
        let flag = match cursor.peek() {
            b'-' => Flags::LEFT_JUSTIFY,
            b'+' => Flags::FORCE_SIGN,
            b' ' => Flags::SPACE_FOR_SIGN,
            b'#' => Flags::ALTERNATE_FORM,
            b'0' => Flags::ZERO_PAD,
            b'\'' => Flags::GROUP_THOUSANDS,
            _ => break,
        };
        flags = flags.with(flag);
        cursor.advance(1);
    }
    // Conflicting flags: left-justifying beats zero padding; `+` beats space.
    if flags.has(Flags::LEFT_JUSTIFY) {
        flags = flags.without(Flags::ZERO_PAD);
    }
    if flags.has(Flags::FORCE_SIGN) {
        flags = flags.without(Flags::SPACE_FOR_SIGN);
    }

    let signed_width = if cursor.peek() == b'*' {
        cursor.advance(1);
        args.next_word() as i32
    } else {
        cursor.parse_decimal()
    };
    // A negative width (from `*`) means "left-justify with the absolute width".
    if signed_width < 0 {
        flags = flags.with(Flags::LEFT_JUSTIFY);
    }
    let min_width = signed_width.unsigned_abs() as usize;

    let mut precision = None;
    if cursor.peek() == b'.' {
        cursor.advance(1);
        let signed_precision = if cursor.peek() == b'*' {
            cursor.advance(1);
            args.next_word() as i32
        } else {
            cursor.parse_decimal()
        };
        // A negative precision counts as "not given".
        precision = usize::try_from(signed_precision).ok();
    }
    // An explicit precision disables zero padding.
    if precision.is_some() {
        flags = flags.without(Flags::ZERO_PAD);
    }

    let arg_size = match (cursor.peek(), cursor.peek_ahead(1)) {
        (b'h', b'h') => {
            cursor.advance(2);
            ArgSize::Char
        }
        (b'h', _) => {
            cursor.advance(1);
            ArgSize::Short
        }
        (b'l', b'l') => {
            cursor.advance(2);
            ArgSize::LongLong
        }
        (b'l', _) => {
            cursor.advance(1);
            ArgSize::Long
        }
        (b'j', _) => {
            cursor.advance(1);
            ArgSize::IntMax
        }
        (b't', _) => {
            cursor.advance(1);
            ArgSize::PtrDiff
        }
        (b'z', _) => {
            cursor.advance(1);
            ArgSize::Size
        }
        _ => ArgSize::Int,
    };

    Directive { flags, min_width, precision, arg_size }
}

// ---------------------------------------------------------------------------------------
// Reading integer arguments.
// ---------------------------------------------------------------------------------------

/// Reads a signed integer argument, sign-extended to 64 bits.
fn next_signed(arg_size: ArgSize, args: &mut impl Args) -> i64 {
    match arg_size {
        ArgSize::Char => args.next_word() as i8 as i64,
        ArgSize::Short => args.next_word() as i16 as i64,
        // On this 32-bit target these are all 32-bit values.
        ArgSize::Int | ArgSize::Long | ArgSize::PtrDiff | ArgSize::Size => args.next_word() as i32 as i64,
        ArgSize::IntMax | ArgSize::LongLong => args.next_double_word() as i64,
    }
}

/// Reads an unsigned integer argument, zero-extended to 64 bits.
fn next_unsigned(arg_size: ArgSize, args: &mut impl Args) -> u64 {
    match arg_size {
        ArgSize::Char => args.next_word() as u8 as u64,
        ArgSize::Short => args.next_word() as u16 as u64,
        ArgSize::Int | ArgSize::Long | ArgSize::PtrDiff | ArgSize::Size => args.next_word() as u64,
        ArgSize::IntMax | ArgSize::LongLong => args.next_double_word(),
    }
}

