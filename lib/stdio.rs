/// Bytes shown per `hex_dump` line.
const HEX_DUMP_LINE_BYTES: usize = 16;

fn push_spaces(line: &mut CBuf<128>, count: usize) {
    for _ in 0..count {
        let _ = line.write_char(' ');
    }
}

/// Dumps `bytes` as hex, 16 per line, to the console.  `first_offset` is the label of the
/// first byte; with `show_ascii` the printable characters are shown alongside.  Each line
/// is built in a buffer and written with a single console call, so lines never interleave.
pub fn hex_dump_bytes(first_offset: usize, bytes: &[u8], show_ascii: bool) {
    let mut offset = first_offset;
    let mut remaining = bytes;
    while !remaining.is_empty() {
        // Lines are aligned to multiples of 16; the first line may start mid-row.
        let blanks_before = offset % HEX_DUMP_LINE_BYTES;
        let count = (HEX_DUMP_LINE_BYTES - blanks_before).min(remaining.len());
        let blanks_after = HEX_DUMP_LINE_BYTES - blanks_before - count;
        let (line_bytes, rest) = remaining.split_at(count);

        let mut line = CBuf::<128>::new();
        let _ = write!(line, "{:08x}  ", offset - blanks_before);
        push_spaces(&mut line, 3 * blanks_before);
        for (column, byte) in (blanks_before..).zip(line_bytes) {
            let separator = if column == HEX_DUMP_LINE_BYTES / 2 - 1 { '-' } else { ' ' };
            let _ = write!(line, "{byte:02x}{separator}");
        }
        if show_ascii {
            push_spaces(&mut line, 3 * blanks_after);
            let _ = line.write_char('|');
            push_spaces(&mut line, blanks_before);
            for &byte in line_bytes {
                let shown = if byte.is_ascii_graphic() || byte == b' ' { byte as char } else { '.' };
                let _ = line.write_char(shown);
            }
            push_spaces(&mut line, blanks_after);
            let _ = line.write_char('|');
        }
        let _ = line.write_char('\n');
        console::write_bytes(line.as_bytes());

        offset = offset.wrapping_add(count);
        remaining = rest;
    }
}

/// C entry point for [`hex_dump_bytes`].
///
/// # Safety
/// `buffer` is readable for `size` bytes.
#[no_mangle]
pub unsafe extern "C" fn hex_dump(first_offset: usize, buffer: *const c_void, size: usize, show_ascii: bool) {
    // SAFETY: caller passes a readable buffer of that size.
    let bytes = unsafe { ffi::slice_from_raw(buffer.cast::<u8>(), size) };
    hex_dump_bytes(first_offset, bytes, show_ascii);
}

/// Prints a byte count in human-readable form, e.g. "256 kB".
#[no_mangle]
pub extern "C" fn print_human_readable_size(size_in_bytes: u64) {
    const UNITS: [&str; 5] = ["bytes", "kB", "MB", "GB", "TB"];
    if size_in_bytes == 1 {
        kprint!("1 byte");
        return;
    }
    // Divide by 1024 until the number is small or we run out of units.
    let mut scaled = size_in_bytes;
    let mut unit_index = 0;
    while scaled >= 1024 && unit_index + 1 < UNITS.len() {
        scaled /= 1024;
        unit_index += 1;
    }
    kprint!("{} {}", scaled, UNITS[unit_index]);
}
